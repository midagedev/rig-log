#!/usr/bin/env python3
"""Render docs/bloomery-bench.md from the bench ledger and its seed.

    render.py [--root DIR]            # rewrite the page below its marker line
    render.py --check [--root DIR]    # 1 when the page is not what the ledger renders, a seed value is
                                      # not stated in its anchor, or a row's anchor is not in log/
    render.py --section-sha ANCHOR    # the sha256 prefix a seed row records for its section
    render.py --self-test

Everything above the marker line is hand-written and kept as it is. Below it: per model and card,
the latest date's windows (bloomery's rows and every reference engine's, the ratio bloomery / that
row computed only inside one window), then the progress of every bloomery series (one setup,
metric and size) by date, with the change from the previous point and from the first. Every
number is a ledger or seed value, or a ratio of two of them computed here.
"""
import argparse
import difflib
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import (BLOOMERY, FAIL, LEDGER, PAGE, SEED, BenchError, read_table, repo_root,  # noqa: E402
                    row_value, section, section_sha, verify_seed_row)

MARKER = ("<!-- generated by tools/bench/render.py from data/bloomery-bench.tsv and "
          "data/bloomery-bench-seed.tsv: do not edit below this line -->")
PLACEHOLDER = "# bloomery bench\n\n(placeholder: the lead's prose goes here)\n\n"
METRIC_ORDER = {"decode": 0, "prompt": 1}


def load(root):
    seed = read_table(os.path.join(root, SEED))
    ledger_path = os.path.join(root, LEDGER)
    ledger = read_table(ledger_path) if os.path.exists(ledger_path) else []
    for i, r in enumerate(seed, 2):
        verify_seed_row(root, f"{SEED}:{i}", r)
    for i, r in enumerate(ledger, 2):
        if r["source"] == "seed":
            raise BenchError(f"{LEDGER}:{i}: a `seed` row belongs in {SEED}")
        section(root, r["anchor"])
    rows = seed + ledger
    seen = {}
    for r in rows:
        k = (r["window"], r["arm"], r["metric"], r["size"])
        if k in seen:
            raise BenchError(f"two rows for window {k[0]}, arm {k[1]}, {k[2]} {k[3]}")
        seen[k] = r
    # Windows in date order, a date's windows in the order the files hold them.
    order = {}
    for r in sorted(rows, key=lambda r: r["date"]):
        order.setdefault(r["window"], len(order))
    return rows, order


def fmt(v):
    if v >= 1000:
        return f"{v:,.0f}"
    if v >= 100:
        return f"{v:.1f}"
    return f"{v:.2f}"


def value_cell(r):
    v = row_value(r)
    if v is None:
        return FAIL
    return ("≥ " if r["status"] == "lower-bound" else "") + fmt(v)


def window_cell(r):
    w = r["window"]
    return w[len(r["date"]) + 1:] if w.startswith(r["date"] + "/") else w


def commit_cell(r):
    feed = [f for f in r["flags"].split("; ") if f.startswith("feed=")]
    return r["bloomery_commit"] + (f" ({feed[0]})" if feed else "")


def link(anchor):
    path, slug = anchor.split("#")
    return f"[{path[9:14]}#{slug}](../{path}#{slug})"


def engine_cell(r):
    if r["engine"] == BLOOMERY and r["arm"] == "ours":
        return BLOOMERY
    return f"{r['engine']} · `{r['arm']}`"


def setup_cell(r):
    feed = [f for f in r["flags"].split("; ") if f.startswith("feed=")]
    return r["setup"] + (" · " + feed[0] if feed else "")


class Notes:
    """Footnotes for statuses other than clean, numbered by first use."""

    def __init__(self):
        self.items = []

    def cell(self, r):
        parts = []
        if r["status_reason"] != "-":
            key = (r["status"], r["status_reason"])
            if key not in self.items:
                self.items.append(key)
            parts.append(f"{r['status']} [{self.items.index(key) + 1}]")
        tags = [t for t in r["tags"].split("; ") if t not in ("-", "no-clean-round")]
        if tags:
            parts.append("; ".join(tags))
        return " · ".join(parts) or "clean"

    def render(self):
        return [f"[{i}] {s}: {why}" for i, (s, why) in enumerate(self.items, 1)]


def row_sort(order):
    return lambda r: (order[r["window"]], METRIC_ORDER[r["metric"]], int(r["size"]),
                      r["engine"] != BLOOMERY)


def ratio_cell(r, rows):
    if r["engine"] == BLOOMERY:
        return "—"
    ref = row_value(r)
    ours = [b for b in rows if b["engine"] == BLOOMERY and b["window"] == r["window"] and b["metric"] == r["metric"]
            and b["size"] == r["size"] and b["file"] == r["file"] and row_value(b) is not None]
    if ref is None or not ours:
        return "—"
    cells = []
    for b in ours:
        q = f"{'≥ ' if b['status'] == 'lower-bound' else ''}{row_value(b) / ref:.3f}"
        cells.append(q if len(ours) == 1 else f"{b['arm']} {q}")
    return " · ".join(cells)


def table(head, lines):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---:" if h in ("크기", "값", "비율", "라운드", "이전 대비", "처음 대비", "처음", "최신")
                                                        else "---" for h in head) + "|"]
    out += ["| " + " | ".join(c.replace("|", "\\|") for c in ln) + " |" for ln in lines]
    return out


# The Summary's model order; a model no prefix names follows these, by name.
MODEL_ORDER = ("DeepSeek-V4.1", "GLM-5.3", "Qwen3.8", "Qwen3.6", "Qwen3-30B")


def model_rank(model):
    for i, p in enumerate(MODEL_ORDER):
        if model.startswith(p):
            return (i, model)
    return (len(MODEL_ORDER), model)


def card_rank(card):
    return (card != "RTX A6000", card)


def series_of(rows):
    """bloomery's series, (model, card, file, setup, metric, size) -> its points in window order."""
    out = {}
    for r in rows:
        if r["engine"] == BLOOMERY:
            out.setdefault((r["model"], r["card"], r["file"], r["setup"], r["metric"], int(r["size"])), []).append(r)
    return out


def summary(rows, order, notes):
    """One row per (model, card, metric): the headline series is the one whose newest point is the
    newest; on a tie the one with more points, then one whose newest point is not a lower bound,
    then the larger size, then the setup's name."""
    best = {}
    for key, pts in series_of(rows).items():
        pts = sorted([r for r in pts if row_value(r) is not None], key=lambda r: order[r["window"]])
        if not pts:
            continue
        model, card, _, setup, metric, size = key
        rank = (order[pts[-1]["window"]], len(pts), pts[-1]["status"] != "lower-bound", size)
        k = (model, card, metric)
        if k not in best or rank > best[k][0] or (rank == best[k][0] and setup < best[k][1][3]):
            best[k] = (rank, key, pts)
    lines = []
    for k in sorted(best, key=lambda k: (model_rank(k[0]), card_rank(k[1]), METRIC_ORDER[k[2]])):
        _, (model, card, _, _, metric, size), pts = best[k]
        first, last = pts[0], pts[-1]
        ratio = f"×{row_value(last) / row_value(first):.3f}" if len(pts) > 1 else "—"
        lines.append([model, card, metric, str(size), setup_cell(last), f"{value_cell(first)} ({first['date']})",
                      f"{value_cell(last)} ({last['date']})", ratio, notes.cell(last), link(last["anchor"])])
    return ["## Summary", ""] + table(["모델", "카드", "지표", "크기", "설정", "처음", "최신", "처음 대비", "상태", "기록"],
                                     lines) + [""]


def render(rows, order):
    notes = Notes()
    groups = {}
    for r in rows:
        groups.setdefault((r["model"], r["card"]), []).append(r)
    keys = sorted(groups, key=lambda k: (k[0], k[1]))
    out = summary(rows, order, notes) + ["## Latest", ""]
    for model, card in keys:
        g = groups[(model, card)]
        dates = [r["date"] for r in g if r["engine"] == BLOOMERY]
        if not dates:
            continue
        latest = [r for r in g if r["date"] == max(dates)]
        latest.sort(key=row_sort(order))
        out += [f"### {model} — {card}", ""]
        files = sorted({r["file"] for r in latest})
        out += [f"Files: {', '.join('`' + f + '`' for f in files)}.", ""]
        lines = [[window_cell(r), r["metric"], r["size"], engine_cell(r), setup_cell(r), r["engine_build"], value_cell(r),
                  ratio_cell(r, latest), f"{r['clean_rounds']}/{r['rounds']}", notes.cell(r), link(r["anchor"])]
                 for r in latest]
        out += table(["창", "지표", "크기", "엔진", "설정", "빌드", "값", "비율", "라운드", "상태", "기록"], lines)
        out.append("")
    out += ["## Progress", ""]
    for model, card in keys:
        ours = [r for r in groups[(model, card)] if r["engine"] == BLOOMERY]
        if not ours:
            continue
        series = {}
        for r in ours:
            series.setdefault((r["file"], r["setup"], r["metric"], int(r["size"])), []).append(r)
        out += [f"### {model} — {card}", ""]
        lines = []
        for (file, setup, metric, size) in sorted(series, key=lambda k: (k[0], k[1], METRIC_ORDER[k[2]], k[3])):
            pts = sorted(series[(file, setup, metric, size)], key=lambda r: order[r["window"]])
            first = prev = None
            for i, r in enumerate(pts):
                v = row_value(r)
                d_prev = f"×{v / prev:.3f}" if v is not None and prev else "—"
                d_first = f"×{v / first:.3f}" if v is not None and first and i else "—"
                label = [setup + (f" · `{file}`" if len({k[0] for k in series}) > 1 else ""), metric, str(size)] \
                    if i == 0 else ["", "", ""]
                lines.append(label + [r["date"], window_cell(r), commit_cell(r), value_cell(r), d_prev, d_first,
                                      notes.cell(r), link(r["anchor"])])
                if v is not None:
                    prev = v
                    first = first or v
        out += table(["설정", "지표", "크기", "날짜", "창", "빌드", "값", "이전 대비", "처음 대비", "상태", "기록"], lines)
        out.append("")
    out += ["## Notes", ""]
    out += ["- 라운드: clean rounds / rounds. 값: the mean over the clean rounds, over all rounds when none is clean "
            "(then 라운드 reads 0/N); `≥`: a lower bound. 비율: bloomery / that row, inside one window only. 창: the "
            "window's id after its date. 빌드 in Progress: the bloomery commit and how the prompt was fed. `unstated`: "
            "the anchor does not state it."]
    out += [f"- {n}" for n in notes.render()]
    return "\n".join(out).rstrip("\n") + "\n"


def page_text(root, generated):
    path = os.path.join(root, PAGE)
    if os.path.exists(path):
        text = open(path, encoding="utf-8").read()
        if MARKER not in text:
            raise BenchError(f"{PAGE}: no marker line; the page is not the renderer's")
        head = text.split(MARKER, 1)[0]
    else:
        head = PLACEHOLDER
    return head + MARKER + "\n\n" + generated


def check(root):
    rows, order = load(root)
    want = page_text(root, render(rows, order))
    path = os.path.join(root, PAGE)
    have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    if have != want:
        diff = difflib.unified_diff(have.splitlines(), want.splitlines(), PAGE, "rendered", lineterm="", n=1)
        raise BenchError(f"{PAGE} is not what render.py produces (run python3 tools/bench/render.py):\n"
                         + "\n".join(list(diff)[:40]))


# --- self-test ---------------------------------------------------------------------------------
SELF_LOG = """<a name="old"></a>
## old

The step read 1,234.5 tok/s and 30.71; ~~99.9~~ corrected. Rounds 20.5 · 21.5.
<a name="new"></a>
## new
"""


def _row(**kw):
    r = dict(date="2026-01-02", window="2026-01-02/new", anchor="log/2026-01-02.md#new", source="new.log",
             source_sha256="0123456789abcdef", model="M-1", file="M-1-Q4_K_M.gguf", card="RTX A6000",
             setup="prompt=lcg", arm="ours", engine=BLOOMERY, engine_build="gen aaaa", flags="x", metric="decode",
             size="6", value="20.000", rounds="2", clean_rounds="2", tags="-", status="clean", status_reason="-",
             bloomery_commit="abc1234")
    r.update(kw)
    return r


def self_test():
    tmp = tempfile.mkdtemp(prefix="bench-render-")
    try:
        return _self_test(tmp)
    finally:
        shutil.rmtree(tmp)


def _self_test(tmp):
    from common import write_table
    os.makedirs(os.path.join(tmp, "log"))
    os.makedirs(os.path.join(tmp, "data"))
    os.makedirs(os.path.join(tmp, "docs"))
    open(os.path.join(tmp, "log/2026-01-01.md"), "w").write(SELF_LOG)
    open(os.path.join(tmp, "log/2026-01-02.md"), "w").write('<a name="new"></a>\n## new\n')
    sha = section_sha(tmp, "log/2026-01-01.md#old")
    seed = [_row(date="2026-01-01", window="2026-01-01/old", anchor="log/2026-01-01.md#old", source="seed",
                 source_sha256=sha, value="30.71", engine_build="unstated", bloomery_commit="0000aaa"),
            _row(date="2026-01-01", window="2026-01-01/old", anchor="log/2026-01-01.md#old", source="seed",
                 source_sha256=sha, value="1234.5", metric="prompt", size="512", bloomery_commit="0000aaa"),
            _row(date="2026-01-01", window="2026-01-01/old", anchor="log/2026-01-01.md#old", source="seed",
                 source_sha256=sha, value="20.5|21.5", size="512", bloomery_commit="0000aaa")]
    ledger = [_row(),
              _row(arm="lcpp", engine="llama.cpp", value="16.000", engine_build="5210c7c"),
              _row(arm="hot", setup="prompt=lcg hot=h", value="24.000", status="lower-bound", status_reason="cold"),
              _row(window="2026-01-02/other", arm="lcpp", engine="llama.cpp", value="10.000"),
              _row(arm="exl3", engine="exllamav3", file="M-1-exl3-4.05", value="5.000"),
              _row(arm="lcppfail", engine="llama.cpp", value=FAIL, clean_rounds="0", tags="fail r1 rc=1"),
              _row(size="1024", clean_rounds="1", tags="excluded r1", status_reason="excluded r1: cold rows"),
              _row(window="2026-01-02/glm", model="GLM-5.3-Flash", file="GLM-5.3-Flash-UD-Q4_K_XL-00001-of-00006.gguf", size="512"),
              _row(window="2026-01-02/glm", model="GLM-5.3-Flash", file="GLM-5.3-Flash-UD-Q4_K_XL-00001-of-00006.gguf", size="1024",
                   value="30.000", status="lower-bound", status_reason="cold")]
    write_table(os.path.join(tmp, SEED), seed)
    write_table(os.path.join(tmp, LEDGER), ledger)
    bad = 0
    rows, order = load(tmp)
    text = render(rows, order)
    again = render(*load(tmp))
    lines = text.split("\n")
    lcpp = [ln for ln in lines if "`lcpp`" in ln and "| new |" in ln]
    other = [ln for ln in lines if "| other |" in ln]
    exl3 = [ln for ln in lines if "`exl3`" in ln]
    fail = [ln for ln in lines if "`lcppfail`" in ln]
    progress = [ln for ln in lines if "| new |" in ln and "abc1234" in ln and "20.00" in ln]
    summ = text.split("## Latest")[0].split("\n")
    summ_rows = [ln for ln in summ if ln.startswith("| ") and not ln.startswith("| 모델")]
    checks = [
        ("summary: one row per (model, card, metric), the listed models first",
         [ln.split(" | ")[0] + " " + ln.split(" | ")[2] for ln in summ_rows]
         == ["| GLM-5.3-Flash decode", "| M-1 decode", "| M-1 prompt"]),
        ("summary: the headline is the series with the newest point and then the most points",
         any("| M-1 | RTX A6000 | decode | 6 |" in ln and "| 30.71 (2026-01-01) | 20.00 (2026-01-02) | ×0.651 |" in ln
             for ln in summ_rows)),
        ("summary: on a tie a lower bound gives way", any("| GLM-5.3-Flash | RTX A6000 | decode | 512 |" in ln
                                                          for ln in summ_rows)),
        ("summary: a series of one point shows — for 처음 대비",
         any("| M-1 | RTX A6000 | prompt | 512 |" in ln and "| 1,234 (2026-01-01) | 1,234 (2026-01-01) | — |" in ln
             for ln in summ_rows)),
        ("the render is deterministic", text == again),
        ("the ratio is computed inside the window, per bloomery arm, a lower bound marked",
         lcpp and "ours 1.250 · hot ≥ 1.500" in lcpp[0] and "| new |" in lcpp[0]),
        ("no ratio against another window's row", other and "| — |" in other[0]),
        ("no ratio against another file", exl3 and "| — |" in exl3[0]),
        ("a FAIL row shows FAIL and no ratio", fail and "| FAIL | — |" in fail[0]),
        ("a lower-bound value carries ≥ and a footnote", "≥ 24.00" in text and "[1] lower-bound: cold" in text),
        ("an excluded round's reason is footnoted on a clean row",
         any("| 1024 |" in ln and "clean [2] · excluded r1" in ln for ln in lines)
         and "[2] clean: excluded r1: cold rows" in text),
        ("progress: the change from the previous and the first point", progress and "×0.651" in progress[0]),
        ("a seed row's `a|b` value renders as the mean", any("| old |" in ln and "| 21.00 |" in ln for ln in lines)),
    ]
    for name, ok in checks:
        if ok:
            print(f"  ok — {name}")
        else:
            print(f"  WRONG — {name}")
            bad += 1
    # FAIL-first: a seed value the section does not state, one only struck through, a changed section
    mangles = [
        ("a seed value with a wrong digit", dict(value="30.72"), "not stated"),
        ("a seed value only inside ~~ ~~", dict(value="99.9"), "not stated"),
        ("a seed value that is the head of a longer number", dict(value="30.7"), "not stated"),
        ("a seed row whose section changed", dict(source_sha256="ffffffffffffffff"), "changed since"),
        ("a seed row whose anchor is not in log/", dict(anchor="log/2026-01-01.md#gone"), "no `<a name"),
        ("a seed row whose model is not its file's", dict(model="M-2"), "is not the file's"),
    ]
    for name, change, needle in mangles:
        s = [dict(seed[0], **change)] + seed[1:]
        write_table(os.path.join(tmp, SEED), s)
        try:
            load(tmp)
            print(f"  NOT CAUGHT — {name}")
            bad += 1
        except BenchError as e:
            print(f"  {'FAIL as required' if needle in str(e) else 'CAUGHT FOR ANOTHER REASON'} — {name}: {e}")
            bad += needle not in str(e)
    write_table(os.path.join(tmp, SEED), seed)
    load(tmp)
    print("  ok — the seed value 1234.5 is found as 1,234.5 (thousands separator)")
    write_table(os.path.join(tmp, LEDGER), ledger + [_row(anchor="log/2026-01-02.md#gone", window="w2")])
    try:
        load(tmp)
        print("  NOT CAUGHT — a ledger row whose anchor is not in log/")
        bad += 1
    except BenchError as e:
        print(f"  FAIL as required — a ledger row whose anchor is not in log/: {e}")
    print("self-test:", "all cases right" if not bad else f"{bad} wrong")
    return 1 if bad else 0


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--root")
    p.add_argument("--check", action="store_true")
    p.add_argument("--section-sha")
    p.add_argument("--self-test", action="store_true")
    a = p.parse_args()
    if a.self_test:
        return self_test()
    root = a.root or repo_root()
    try:
        if a.section_sha:
            print(section_sha(root, a.section_sha))
        elif a.check:
            check(root)
            print(f"check-bench: {PAGE} is current; every seed value is stated in its anchor; every anchor exists")
        else:
            rows, order = load(root)
            text = page_text(root, render(rows, order))
            with open(os.path.join(root, PAGE), "w", encoding="utf-8") as fh:
                fh.write(text)
            print(f"render: {PAGE} from {len(rows)} rows")
    except BenchError as e:
        print(f"render.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
